// =========================
// POPULATE SIDEBAR
// =========================

function populateSidebar() {

    const categories = [
        "frontend",
        "fullstack",
        "wordpress"
    ];

    categories.forEach(cat => {

        const listEl = document.getElementById(`${cat}-list`);

        for (let key in projects) {

            if (projects[key].category === cat) {

                const li = document.createElement("li");

                const button = document.createElement("button");

                button.type = "button";

                button.textContent = projects[key].title;

                button.className =
                    "project-link w-full rounded-md px-3 py-2 text-left text-sm text-zinc-300 transition hover:bg-zinc-800 hover:text-white";

                button.onclick = () => showProject(key);

                li.appendChild(button);

                listEl.appendChild(li);
            }
        }
    });
}


// =========================
// TOGGLE CATEGORY
// =========================

function toggleCategory(cat) {

    const listEl = document.getElementById(`${cat}-list`);

    listEl.classList.toggle("hidden");
}


